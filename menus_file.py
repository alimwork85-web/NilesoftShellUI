import glob
import os
import shutil
import time

import theme_file
from theme_file import AppError

MENUS_FILE = os.path.join(theme_file.shell_dir(), "imports", "ui-menus.nss")
IMPORT_LINE = "import 'imports/ui-menus.nss'"
HEADER = "// Generated by Nilesoft Shell UI: Shell menus (lines starting with // are hidden)"

# الترتيب هو ترتيب ظهورها في القائمة
MENUS = {
    "pin": 'menu(mode="multiple" title="Pin/Unpin" image=icon.pin) {}',
    "more": "menu(mode=\"multiple\" title=title.more_options image=icon.more_options) {}",
    "terminal": "import 'imports/terminal.nss'",
    "file-manage": "import 'imports/file-manage.nss'",
    "develop": "import 'imports/develop.nss'",
    "goto": "import 'imports/goto.nss'",
    "taskbar": "import 'imports/taskbar.nss'",
}
DEFAULT_OFF = {"develop"}  # كانت غير مستوردة في shell.nss


def is_linked():
    try:
        with open(os.path.join(theme_file.shell_dir(), "shell.nss"), encoding="utf-8-sig") as f:
            return IMPORT_LINE in f.read()
    except OSError:
        return False


def load():
    """يرجع {المفتاح: ظاهرة؟}."""
    if not os.path.exists(MENUS_FILE):
        return {k: k not in DEFAULT_OFF for k in MENUS}
    with open(MENUS_FILE, encoding="utf-8-sig") as f:
        lines = {line.strip() for line in f}
    return {k: v in lines for k, v in MENUS.items()}


def build(shown):
    lines = [HEADER]
    for k, v in MENUS.items():
        lines.append(v if shown.get(k, k not in DEFAULT_OFF) else "// " + v)
    return "\n".join(lines) + "\n"


def save(shown):
    if not isinstance(shown, dict) or set(shown) - set(MENUS):
        raise AppError("قائمة غير معروفة", "Unknown menu")
    text = build(shown)
    os.makedirs(theme_file.BACKUP_DIR, exist_ok=True)
    if os.path.exists(MENUS_FILE):
        stamp = time.strftime("%Y%m%d-%H%M%S")
        shutil.copy2(MENUS_FILE, os.path.join(theme_file.BACKUP_DIR, f"ui-menus-{stamp}.nss"))
        for p in sorted(glob.glob(os.path.join(theme_file.BACKUP_DIR, "ui-menus-*.nss")))[:-theme_file.KEEP_BACKUPS]:
            os.remove(p)
    try:
        with open(MENUS_FILE, "w", encoding="utf-8-sig", newline="\r\n") as f:
            f.write(text)
    except PermissionError:
        raise AppError("لا توجد صلاحية كتابة على ملف القوائم: " + MENUS_FILE,
                       "No write permission on the menus file: " + MENUS_FILE)
    return load()


if __name__ == "__main__":  # فحص ذاتي: الحفظ ثم القراءة يرجعان نفس الحالة
    import tempfile
    MENUS_FILE = os.path.join(tempfile.mkdtemp(), "ui-menus.nss")
    want = {k: i % 2 == 0 for i, k in enumerate(MENUS)}
    assert save(want) == want, load()
    assert load() == want
    print("ok")
